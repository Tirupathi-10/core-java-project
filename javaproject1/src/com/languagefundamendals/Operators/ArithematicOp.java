package com.languagefundamendals.Operators;

public class ArithematicOp {

	public static void main(String[] args) {
		int a=30;
		int b=20;
		
		float c=10.5f;
		float d=20.5f;
		
		double e=6.5;
		double f=30.4567;
		
		char x=25;
		char y=25;
		
		System.out.println("Addition of two numbers:"+(a+b));
		System.out.println("Subtraction of two numbers:"+(a-b));
		System.out.println("Mulriplication of two numbers:"+a*b);
		System.out.println("Division of two numbers:"+a/b);
		System.out.println("Modules of two numbers:"+a%b);
		System.out.println("---------------------------------");
		System.out.println("Addition of two numbers:"+(c+d));
		System.out.println("Subtraction of two numbers:"+(c-d));
		System.out.println("Mulriplication of two numbers:"+c*d);
		System.out.println("Division of two numbers:"+c/d);
		System.out.println("Modules of two numbers:"+c%d);
		
		System.out.println("---------------------------------");
		System.out.println("Addition of two numbers:"+(e+f));
		System.out.println("Subtraction of two numbers:"+(e-f));
		System.out.println("Mulriplication of two numbers:"+e*f);
		System.out.println("Division of two numbers:"+e/f);
		System.out.println("Modules of two numbers:"+e%f);
		System.out.println("---------------------------------");
		
		System.out.println("Addition of two numbers:"+(x+y));
		System.out.println("Subtraction of two numbers:"+(x-y));
		System.out.println("Mulriplication of two numbers:"+x*y);
		System.out.println("Division of two numbers:"+x/y);
		System.out.println("Modules of two numbers:"+x%y);
	}
	

}
